def nb_cdf(mean, r, kmax):
    """CDF of 1 + NegBin(r, p) with the given mean (dwell time in intervals)."""
    p = r / (mean - 1 + r)
    cdf, acc = [], 0.0
    for k in range(1, kmax + 1):
        j = k - 1
        acc += math.comb(j + r - 1, j) * p ** r * (1 - p) ** j
        cdf.append(acc)
    return cdf



ALPHA_OFF, CHI_H, SLEEP_SAVE = 0.5, 0.6, 0.9   # wear model: sleep AF, cycling weight [h], fraction of port power saved by sleeping
COST_CH, COST_TR = 0.002, 0.0008               # lambda_R*R per change, lambda_W*W per transition (units: daily always-on port energy)


def af(S, tr, links):
    tau = S / 100.0 / SLEEP_SAVE
    f = tr / links / 24.0
    return 1.0 - (1.0 - ALPHA_OFF) * tau + CHI_H * f


def cost(S, ch, tr):
    return (1.0 - S / 100.0) + COST_CH * ch + COST_TR * tr



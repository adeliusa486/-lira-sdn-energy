"""E18 (no wear price) and E19 (Nobel-Germany noise structure).

E18 repeats the E1 comparison with lambda_W = 0: oracle labels, tuning, training and the reported
cost J then contain energy and reconfiguration only, so the wear credit of sleeping links cannot
drive the ranking. Every method is retrained.

E19 repeats the base-scenario E1 comparison on Nobel-Germany variants whose log-normal noise is
temporally correlated (AR(1) in log space, same marginal sigma) or weaker (sigma halved). The
series are generated by experiments/make_nobel_variants.py and get their own library.

Both include the static rule of E17 (most frequent training-oracle configuration + fallback).
Output: results/<E18_no_wear|E19_noise>/<topo>_<scenario>_{runs.csv,daily_J.npz}, stats.csv
Usage:  python experiments/run_variant.py --exp E18 [--topos ...]
        python experiments/run_variant.py --exp E19 --topos nobel_ar05 nobel_ar09 nobel_s06
"""
import argparse
import time

from common import *  # noqa: F401,F403
from lira.policy.models import ConstantModel
from run_main import SCENARIOS, SEEDS, log, scenario_available
from run_static import static_config


def run_setting(ctx, topo, sc, w_mult):
    lr, lw = prices(ctx, 1.0, w_mult)
    rows, daily = [], {}

    def add(method, seed, seq, **kw):
        m, dly = evaluate(ctx, "test", seq, lr, lw, **kw)
        rows.append({"topology": topo, "scenario": sc, "w_mult": w_mult, "method": method,
                     "seed": seed, **m})
        daily[f"{method}_s{seed}"] = dly

    add("B0", 0, always_on_seq(ctx, "test"))
    add("O*", 0, oracle_seq(ctx, "test", lr, lw))
    seq, rt = run_b2(ctx, lr, lw, forecast="naive")
    add("B2", 0, seq, lat=rt)
    c = static_config(ctx, lr, lw)
    pol = LiRA()
    pol.K, pol.lam_R, pol.lam_W, pol.model = ctx.K, lr, lw, ConstantModel(c)
    seq, _, fb = pol.predict(ctx, "test")
    add("Static", 0, seq, fb=fb)
    best_rounds = []
    for s in SEEDS:
        fam, finfo = run_b4_family(ctx, lr, lw, seed=s)
        add("B4", s, fam["B4"], fb=finfo["B4_fallback"])
        add("B6", s, fam["B6"])
        add("B7", s, fam["B7"])
        seq, lat, fb, p = run_lira(ctx, lr, lw, seed=s)
        add("LiRA", s, seq, lat=lat, fb=fb)
        best_rounds.append(p.best_round)
        log(topo, sc, "w_mult", w_mult, "seed", s)
    for r in rows:
        r["lira_round0_runs"] = int(sum(b == 0 for b in best_rounds))
    return rows, daily


def stats(d, topos, scenarios):
    rows = []
    for topo in topos:
        for sc in scenarios:
            f = d / f"{topo}_{sc}_daily_J.npz"
            if not f.exists():
                continue
            z = np.load(f)
            mean = lambda m: np.mean([z[f"{m}_s{s}"] for s in SEEDS], axis=0)
            comps = [("B4", mean("B4")), ("B6", mean("B6")), ("B2", z["B2_s0"]), ("Static", z["Static_s0"])]
            p = [wilcoxon_daily(mean("LiRA"), x) for _, x in comps]
            for (name, x), pv, pa in zip(comps, p, holm(p)):
                diff = mean("LiRA") - x
                rows.append({"topology": topo, "scenario": sc, "comparison": f"LiRA vs {name}",
                             "days": len(diff), "mean_daily_J_diff": float(diff.mean()),
                             "p_raw": pv, "p_holm": pa,
                             "lira_better_days_pct": float(100 * (diff < 0).mean())})
    pd.DataFrame(rows).to_csv(d / "stats.csv", index=False)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", required=True, choices=["E18", "E19"])
    ap.add_argument("--topos", nargs="+", default=list(TOPOS))
    ap.add_argument("--scenarios", nargs="+", default=None)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if a.exp == "E18":
        d, w_mult, scs = out_dir("E18_no_wear"), 0.0, a.scenarios or list(SCENARIOS)
    else:
        d, w_mult, scs = out_dir("E19_noise"), 1.0, a.scenarios or ["base"]
    for topo in a.topos:
        for sc in scs:
            tag = f"{topo}_{sc}"
            if (d / f"{tag}_runs.csv").exists() and not a.force:
                continue
            if not scenario_available(topo, sc):
                log("skip (library missing)", tag)
                continue
            t0 = time.time()
            ctx = build_ctx(topo, 32, **SCENARIOS[sc])
            rows, daily = run_setting(ctx, topo, sc, w_mult)
            pd.DataFrame(rows).to_csv(d / f"{tag}_runs.csv", index=False)
            np.savez_compressed(d / f"{tag}_daily_J.npz", **daily)
            log(a.exp, tag, f"finished in {time.time() - t0:.0f}s")
    stats(d, a.topos, scs)
